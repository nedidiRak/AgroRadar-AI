const errors = [], requests = []
page.on('pageerror', e => errors.push(e.message))
page.on('request', req => {if (new URL(req.url()).pathname.startsWith('/api/')) requests.push(req.method()+' '+new URL(req.url()).pathname)})
const tile = type => page.locator(`[data-widget="${type}"]`).first()
async function click(name) { await button(page,name).click() }
async function save() {
  await Promise.all([page.waitForResponse(r => r.url().endsWith('/api/me/layouts') && r.request().method()==='PUT' && r.ok()), click('Сохранить')])
  await button(page,'Настроить интерфейс').waitFor()
}
async function openTemplate(name) { await page.getByLabel('Шаблон для компьютера').selectOption(name) }
async function geometry() {
  const intersections = await page.locator('.studio-tile').evaluateAll(nodes => nodes.flatMap((node,i) => {
    const a=node.getBoundingClientRect()
    return nodes.slice(i+1).filter(b => {const r=b.getBoundingClientRect(); return a.left<r.right-1 && a.right>r.left+1 && a.top<r.bottom-1 && a.bottom>r.top+1}).map(b=>node.dataset.widget+'/'+b.dataset.widget)
  }))
  assert.deepEqual(intersections,[])
}
