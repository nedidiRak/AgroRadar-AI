def retrieve_notes(crop: str, risk_level: str) -> list[dict[str, str]]:
    notes = [NOTES['weather'], NOTES['water'], NOTES['operations']]
    if risk_level in ('high', 'medium'):
        notes.append(NOTES['frost'])
    low = crop.casefold()
    for terms, name in [
        (('пшениц',), 'wheat'), (('кукуруз',), 'corn'), (('подсолнеч',), 'sunflower'),
        (('соя', 'сои', 'соев'), 'soy'), (('свёкл', 'свекл'), 'beet'),
        (('рапс',), 'rapeseed'), (('ячмен', 'ячмень'), 'barley'),
    ]:
        if any(term in low for term in terms):
            notes.append(NOTES[name])
            break
    return [{'id': label, 'text': description} for label, description in notes]
